def select_claims(claims: list[dict[str, str]], keywords: list[str], limit: int = 8) -> list[dict[str, str]]:
    scored = []
    for claim in claims:
        hay = " ".join([claim.get("claim_text", ""), claim.get("concept", ""), claim.get("mechanism", ""), claim.get("project_use", "")]).lower()
        score = sum(1 for word in keywords if word.lower() in hay)
        if score:
            scored.append((score, claim))
    scored.sort(key=lambda x: (-x[0], x[1]["claim_id"]))
    return [claim for _, claim in scored[:limit]]


