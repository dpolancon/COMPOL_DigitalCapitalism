def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def write_csv(path: Path, rows: list[dict[str, Any]], columns: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({col: row.get(col, "") for col in columns})


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    if not text.startswith("---"):
        return {}, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text
    fm_text = parts[1]
    body = parts[2]
    fm: dict[str, str] = {}
    for line in fm_text.splitlines():
        if ":" not in line or line.strip().startswith("#"):
            continue
        key, value = line.split(":", 1)
        value = value.strip().strip('"').strip("'")
        fm[key.strip()] = value
    return fm, body


def section(text: str, heading: str) -> str:
    pattern = re.compile(rf"^##\s+{re.escape(heading)}\s*$", re.MULTILINE)
    match = pattern.search(text)
    if not match:
        return ""
    start = match.end()
    next_match = re.search(r"^##\s+", text[start:], flags=re.MULTILINE)
    end = start + next_match.start() if next_match else len(text)
    return text[start:end].strip()


def first_sentence(text: str, max_len: int = 700) -> str:
    cleaned = re.sub(r"\s+", " ", strip_markdown(text)).strip()
    cleaned = cleaned.strip("- ")
    if not cleaned:
        return ""
    split = re.split(r"(?<=[.!?])\s+", cleaned)
    sentence = split[0] if split else cleaned
    if len(sentence) > max_len:
        sentence = sentence[:max_len].rsplit(" ", 1)[0] + "..."
    return sentence


def strip_markdown(text: str) -> str:
    text = re.sub(r"\[\[([^\]]+)\]\]", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"[*_`>#]", "", text)
    text = re.sub(r"\s+", " ", text)
    return text.strip()


def bullet_value(text: str, label: str) -> str:
    pattern = re.compile(rf"^-\s+\*\*{re.escape(label)}\*\*:\s*(.*)$", re.MULTILINE)
    match = pattern.search(text)
    return match.group(1).strip() if match else ""


def mechanism_bullets(distilled: str) -> list[str]:
    lines = distilled.splitlines()
    bullets: list[str] = []
    in_mechanism = False
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("- **Mechanism**"):
            in_mechanism = True
            continue
        if in_mechanism and stripped.startswith("- **"):
            break
        if in_mechanism and stripped.startswith("- "):
            bullets.append(stripped[2:].strip())
    return bullets


def page_ref(evidence: str) -> str:
    match = re.search(r"Page\(s\):\s*([^\n]+)", evidence, flags=re.IGNORECASE)
    if not match:
        return ""
    value = match.group(1).strip()
    if "unknown" in value.lower() or "page_unknown" in value.lower():
        return ""
    return value


def evidence_anchor(evidence: str) -> str:
    lines = [line.strip() for line in evidence.splitlines() if line.strip()]
    return " ".join(lines[:3])[:900]


def concept_for(text: str) -> str:
    low = text.lower()
    for concept, aliases in CONCEPT_ALIASES.items():
        candidates = [concept] + aliases
        for candidate in candidates:
            if candidate.lower() in low:
                return concept
    return "land"


def dimension_for(text: str, tag: str = "") -> str:
    low = f"{tag} {text}".lower()
    if any(word in low for word in ["definition", "difference", "distinguish", "concept"]):
        return "definition"
    if any(word in low for word in ["condition", "causal", "chain", "affect", "because"]):
        return "causality"
    if any(word in low for word in ["p_t", "k_t", "r ", " r.", " g", "sigma", "elasticity", "parameter", "variable", "$"]):
        return "variables_parameters"
    if any(word in low for word in ["evidence", "empirical", "measurement", "theorem", "formal", "model"]):
        return "theory_evidence"
    return "mechanism"


def mechanism_for(text: str) -> str:
    low = text.lower()
    for mechanism, words in MECHANISM_RULES.items():
        if any(word.lower() in low for word in words):
            return mechanism
    return ""


