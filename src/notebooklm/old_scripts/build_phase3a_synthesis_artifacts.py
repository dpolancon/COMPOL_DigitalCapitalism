def build_question_claims(q_dir: Path, registry: dict[str, Any], papers_by_id: dict[str, dict[str, Any]]) -> list[dict[str, str]]:
    claims: list[dict[str, str]] = []
    for note_path in sorted(q_dir.glob("PDF*_Q*.md")):
        text = note_path.read_text(encoding="utf-8")
        fm, body = split_frontmatter(text)
        note_id = fm.get("note_id") or note_path.stem
        source_id = fm.get("source_id", "")
        paper = papers_by_id.get(source_id, {})
        paper_key = paper.get("citation_key", "")
        question_id = fm.get("question_id", note_id)
        cluster_id = fm.get("cluster_id", paper.get("cluster_id", ""))
        tag = fm.get("question_tag", "")
        distilled = section(body, "Distilled note")
        evidence = section(body, "Evidence / page anchors")
        page = page_ref(evidence)
        anchor = evidence_anchor(evidence)
        seq = 1
        entries = [
            bullet_value(distilled, "Core claim"),
            bullet_value(distilled, "Formal object/result, if any"),
            bullet_value(distilled, "Critical caveat"),
        ]
        entries.extend(mechanism_bullets(distilled))
        seen = set()
        for entry in entries:
            if not entry or entry.lower() in {"none", "not applicable", "n/a"}:
                continue
            clean_key = strip_markdown(entry).lower()
            if clean_key in seen:
                continue
            seen.add(clean_key)
            claims.append(make_claim(
                note_id=note_id,
                seq=seq,
                text=entry,
                source_id=source_id,
                question_id=question_id,
                paper_key=paper_key,
                page=page,
                note_path=note_path,
                cluster_id=cluster_id,
                tag=tag,
                anchor=anchor,
            ))
            seq += 1
    return claims


def parse_table_rows(table_section: str) -> list[list[str]]:
    rows = []
    for line in table_section.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|") or "---" in stripped:
            continue
        cells = [cell.strip() for cell in stripped.strip("|").split("|")]
        if cells and cells[0] == "Source ID":
            continue
        if len(cells) >= 5:
            rows.append(cells[:5])
    return rows


