def resolve_note_dirs() -> tuple[Path, Path, list[str]]:
    notes_root = ROOT / "03_notes"
    questions = notes_root / "questions"
    clusters = notes_root / "clusters"
    notes = []
    if questions.exists() and clusters.exists():
        notes.append("Using canonical Phase 3A note paths: 03_notes/questions and 03_notes/clusters.")
        return questions, clusters, notes
    fallback_q = ROOT / "notes" / "questions"
    fallback_c = ROOT / "notes" / "clusters"
    if fallback_q.exists() and fallback_c.exists():
        notes.append("Canonical 03_notes paths were absent; using fallback notes/questions and notes/clusters.")
        return fallback_q, fallback_c, notes
    raise FileNotFoundError("Could not find either 03_notes/{questions,clusters} or notes/{questions,clusters}.")


