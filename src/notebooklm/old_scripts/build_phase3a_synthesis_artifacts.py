def make_claim(
    note_id: str,
    seq: int,
    text: str,
    source_id: str,
    question_id: str,
    paper_key: str,
    page: str,
    note_path: Path,
    cluster_id: str = "",
    cluster_question_id: str = "",
    tag: str = "",
    anchor: str = "",
    comment: str = "",
) -> dict[str, str]:
    clean = first_sentence(text)
    dimension = dimension_for(clean, tag)
    concept = concept_for(clean)
    mechanism = mechanism_for(clean)
    return {
        "claim_id": f"CLM_{note_id}_{seq:03d}",
        "source_id": source_id,
        "question_id": question_id,
        "paper_key": paper_key,
        "page_ref": page,
        "dimension": dimension,
        "concept": concept,
        "definition": clean if dimension == "definition" else "",
        "mechanism": mechanism,
        "causal_chain": clean if dimension in {"causality", "mechanism"} else "",
        "variables_parameters": variables_for(clean),
        "theory_evidence_status": theory_status(clean, tag),
        "claim_text": clean,
        "project_use": project_use(clean),
        "validation_status": validation_for(page, clean),
        "reviewer_comment": comment or ("Needs precise page verification before memo drafting." if not page else "NotebookLM-backed paraphrase from completed note; verify exact wording before final quotation."),
        "note_path": rel(note_path),
        "cluster_id": cluster_id,
        "cluster_question_id": cluster_question_id,
        "evidence_anchor": anchor,
        "quote_or_paraphrase": "paraphrase",
        "memo_section_target": memo_target(clean),
        "confidence": "medium" if page else "low",
    }


